import fs from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.LCS_PLAYWRIGHT_MODULE || 'playwright');
const out = 'docs/lcs-web-v2/validation';
const deploy = JSON.parse(fs.readFileSync(`${out}/deployment.json`, 'utf8'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, locale: 'en-US' });
const page = await context.newPage();
const errors = [], failures = [], cases = [];
page.on('pageerror', error => errors.push(error.message));
page.on('requestfailed', request => failures.push(request.url()));
fs.mkdirSync(`${out}/public`, { recursive: true });
try {
  await page.goto(`${deploy.site}?page=output&lang=en`);
  await page.getByText('Output Settings', { exact: true }).first().waitFor();
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('.lcs-web-output-page select').count(), 6);
  await page.screenshot({ path: `${out}/public/output-en.jpg`, quality: 80 });
  await page.locator('.lcs-web-output-page select').nth(1).selectOption('localDirector');
  await page.locator('.lcs-web-language-select').selectOption('zh');
  assert.equal(await page.locator('.lcs-web-output-page select').nth(1).inputValue(), 'localDirector');
  await page.screenshot({ path: `${out}/public/output-zh.jpg`, quality: 80 });
  await page.locator('.lcs-web-language-select').selectOption('en');
  for (let i = 0; i < 2; i++) {
    await page.locator('.lcs-web-output-page').getByRole('button', { name: 'Display Settings', exact: true }).nth(i).click();
    await page.getByRole('dialog').getByRole('button', { name: 'HDMI Output', exact: true }).click();
    assert.equal(await page.getByRole('dialog').locator('input[type=range]').count(), 4);
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await page.locator('.lcs-web-output-page').getByRole('button', { name: 'Audio Settings', exact: true }).nth(i).click();
    assert.match(await page.getByRole('dialog').innerText(), /REC/);
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  }
  cases.push('Public output page, locale stability, both HDMI display/audio dialogs');
  await page.getByRole('button', { name: 'Text Overlays', exact: true }).click();
  assert.equal(new URL(page.url()).pathname, '/q/lcs/');
  assert.equal(new URL(page.url()).searchParams.get('page'), 'subtitle');
  await page.reload();
  await page.locator('.lcs-web-subtitle-page').waitFor();
  assert.equal(await page.locator('.lcs-web-subtitle-page select').first().locator('option').count(), 6);
  await page.locator('.lcs-web-subtitle-page select').last().selectOption('scrollRight');
  cases.push('Public navigation, refresh, six fonts and Scroll Right');
  await page.getByRole('button', { name: 'Tracking Settings', exact: true }).click();
  assert.equal(await page.locator('option[value=protocol4]').count(), 2);
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.locator('.lcs-web-program-preview img').waitFor();
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('img').evaluateAll(images => images.filter(i => !i.complete || !i.naturalWidth).length), 0);
  await page.screenshot({ path: `${out}/public/home-en.jpg`, quality: 80 });
  cases.push('Public tracking Protocol 4 and Home preview images');
  assert.deepEqual(errors, []);
  assert.deepEqual(failures, []);
  await page.goto('https://toastmasterslee.github.io/q/');
  await page.waitForLoadState('networkidle');
  assert.ok((await page.locator('body').innerText()).length > 100);
  await page.screenshot({ path: `${out}/public/architecture-root.jpg`, quality: 80 });
  cases.push('Existing architecture root still renders');
  const report = { site: deploy.site, commit: deploy.commit, viewport: '1366x768', browser: 'Chrome, anonymous independent profile', cases, errors, requestFailures: failures, result: 'passed' };
  fs.writeFileSync(`${out}/public-browser-verification.json`, JSON.stringify(report, null, 2) + '\n');
  deploy.status = 'published_and_verified';
  fs.writeFileSync(`${out}/deployment.json`, JSON.stringify(deploy, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }

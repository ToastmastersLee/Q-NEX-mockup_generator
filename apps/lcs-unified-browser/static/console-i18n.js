export const languages = ['zh','en','fr'];
export function translator(lang){
  const i=Math.max(0,languages.indexOf(lang));
  return (key,values={})=>{
    let value=rows[key]?.[i] || key;
    return value.replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??''));
  };
}
